"""Standard vs custom board on real photos. Run from the repo root:  python -m calib.run_real_compare

Writes results/real/*.csv and results/real/report.md. Everything here is computed, nothing typed in.
"""
import csv, glob, os, sys
import numpy as np
from calib.board import BoardModel
from calib.custom_board import CustomBoardModel
from calib.real_calibrate import (detect_views, opencv_charuco_views, opencv_calibrate)
from synthetic_calib.joint_refine import calibrate_full
from synthetic_calib.sweep import pick_subset

OUT = "results/real"
KEY = lambda s: int(os.path.basename(s).split("_")[1].split(".")[0])
PARAMS = ["fx", "fy", "cx", "cy", "k1", "k2"]


def paths(tag):
    return sorted(glob.glob(f"data/set_{tag}/*.jpeg"), key=KEY)


def row(label, method, r_or_dict, n_views, n_pts, size):
    K, d = r_or_dict["K"] if isinstance(r_or_dict, dict) else r_or_dict.K, \
        r_or_dict["dist"] if isinstance(r_or_dict, dict) else r_or_dict.dist
    g = (lambda k: r_or_dict[k]) if isinstance(r_or_dict, dict) else (lambda k: getattr(r_or_dict, k))
    return dict(setup=label, method=method, views=n_views, points=n_pts, width=size[0],
                fx=K[0, 0], fy=K[1, 1], cx=K[0, 2], cy=K[1, 2], k1=d[0], k2=d[1],
                mean_error=g("mean_error"), rms_error=g("rms_error"),
                fx_over_width=K[0, 0] / size[0], cx_over_width=K[0, 2] / size[0], cy_over_width=K[1, 2] / size[0])


def calibrate_both(label, views, size, rows):
    n = sum(len(v["ids"]) for v in views)
    rows.append(row(label, "ours", calibrate_full(views, size), len(views), n, size))
    rows.append(row(label, "opencv (same corners)", opencv_calibrate(views, size), len(views), n, size))


def bootstrap(views, size, n_sub=20, frac=0.7, seed=1):
    """Spread of each parameter over random subsets of the views (our calibration)."""
    k = max(4, int(round(frac * len(views))))
    out = []
    for s in range(n_sub):
        idx = pick_subset(len(views), k, s, seed=seed)
        try:
            r = calibrate_full([views[i] for i in idx], size)
            out.append([r.K[0, 0], r.K[1, 1], r.K[0, 2], r.K[1, 2], r.dist[0], r.dist[1], r.mean_error])
        except Exception:
            pass
    a = np.array(out)
    return dict(n_ok=len(a), subset_size=k, **{p: (a[:, i].mean(), a[:, i].std(ddof=1)) for i, p in enumerate(PARAMS)},
                mean_error=(a[:, 6].mean(), a[:, 6].std(ddof=1)))


def main():
    os.makedirs(OUT, exist_ok=True)
    rows, boots = [], {}

    # ---- standard board, Set A
    std = BoardModel()
    va, sk, size_a = detect_views(std, paths("a"))
    print("A views", len(va), "skipped", [(os.path.basename(p), r) for p, r in sk])
    calibrate_both("A standard", va, size_a, rows)
    ref = opencv_charuco_views(paths("a"))
    rows.append(row("A standard", "opencv (own ChArUco corners)", opencv_calibrate(ref, size_a), len(ref),
                    sum(len(v["ids"]) for v in ref), size_a))
    boots["A standard"] = bootstrap(va, size_a)

    # ---- custom board, Sets B, D (and both), with and without the diagonal junctions
    for diag in (False, True):
        cm = CustomBoardModel(diagonal_junctions=diag)
        tag = "custom+diag" if diag else "custom"
        vb, _, size_b = detect_views(cm, paths("b"))
        vd, _, size_d = detect_views(cm, paths("d"))
        for name, vs in (("B", vb), ("D", vd), ("B+D", vb + vd)):
            calibrate_both(f"{name} {tag}", vs, size_b, rows)
            if not diag:
                boots[f"{name} {tag}"] = bootstrap(vs, size_b)
        if not diag:
            per_view = [dict(name=v["name"], markers=v["n_markers"], corners_predicted=v["n_pred"],
                             corners_used=len(v["ids"]), corners_rejected=v["n_rejected"]) for v in vb + vd]
            r = calibrate_full(vb + vd, size_b)
            for pv, e in zip(per_view, r.view_errors):
                pv["mean_error_px"] = float(e)
            with open(f"{OUT}/per_view_custom.csv", "w", newline="") as f:
                w = csv.DictWriter(f, fieldnames=list(per_view[0])); w.writeheader(); w.writerows(per_view)

    with open(f"{OUT}/calibration_summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    with open(f"{OUT}/bootstrap_spread.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["setup", "subsets_ok", "subset_size"] + [f"{p}_{s}" for p in PARAMS + ["mean_error"] for s in ("mean", "std")])
        for k, b in boots.items():
            w.writerow([k, b["n_ok"], b["subset_size"]] + [x for p in PARAMS + ["mean_error"] for x in b[p]])
    write_report(rows, boots)


def write_report(rows, boots):
    L = ["# Real-image calibration: standard vs custom board", "",
         "Generated by `python -m calib.run_real_compare`. Raw sensor pixels (EXIF rotation ignored).", "",
         "## Calibration summary", "",
         "| setup | method | views | points | fx | fy | cx | cy | k1 | k2 | mean err px | rms px |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['setup']} | {r['method']} | {r['views']} | {r['points']} | {r['fx']:.1f} | {r['fy']:.1f} | "
                 f"{r['cx']:.1f} | {r['cy']:.1f} | {r['k1']:.4f} | {r['k2']:.4f} | {r['mean_error']:.3f} | {r['rms_error']:.3f} |")
    L += ["", "## Spread over random subsets (70% of the views, ours)", "",
          "| setup | subsets | views each | fx mean ± std | cx mean ± std | cy mean ± std | k1 mean ± std |", "|---|---|---|---|---|---|---|"]
    for k, b in boots.items():
        f = lambda p, d=1: f"{b[p][0]:.{d}f} ± {b[p][1]:.{d}f}"
        L.append(f"| {k} | {b['n_ok']} | {b['subset_size']} | {f('fx')} | {f('cx')} | {f('cy')} | {f('k1', 4)} |")
    open(f"{OUT}/report.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
